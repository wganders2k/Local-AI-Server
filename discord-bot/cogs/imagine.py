"""
/imagine — an image from a text prompt.

Text only, by the user's decision (2026-11-12): the concern is server members
being depicted negatively, and a seed image (someone's photo or avatar) is how
that would happen. So the command takes no attachment, and the proxy refuses
image inputs on its side too (proxy/imagegen.py) — two independent locks.
Prompt content is otherwise unrestricted.

The image is generated by the proxy's image server, under the same GPU lease
as chat; see docs/plans/image-gen.md. If the user sets `rewrite` (required), the
prompt is first expanded by the mimic base (prompts/imagine_rewrite.md); any
failure there sends the original instead, so a rewrite never costs an image.
"""

import io
import logging
import time
from typing import Optional

import discord
from discord import app_commands
from discord.ext import commands

from cogs.common import admit
from config import (
    IMAGINE_MAX_DETAIL_CHARS,
    IMAGINE_MAX_IMAGES,
    IMAGINE_MAX_PROMPT_CHARS,
    IMAGINE_MODEL_LABEL,
    IMAGINE_REWRITE_MAX_CHARS,
    IMAGINE_REWRITE_MAX_TOKENS,
    IMAGINE_REWRITE_MODEL,
    IMAGINE_REWRITE_TEMPERATURE,
    IMAGINE_SHAPES,
)
from prompt_loader import load
from proxy_client import ProxyClient, ProxyError

logger = logging.getLogger("mimic-bot.cogs.imagine")

_SHAPE_CHOICES = [app_commands.Choice(name=name, value=size) for name, size in IMAGINE_SHAPES.items()]
_DEFAULT_SIZE = next(iter(IMAGINE_SHAPES.values()))
_EMBED_FIELD_MAX = 1024  # Discord's limit on an embed field's value
# The detail options, as each is labelled in the prompt. Plain labelled
# sentences: the rewriter reads them as the user's picks, and the image model follows
# them as they are when nothing rewrites them.
_DETAILS = (("style", "Art style"), ("mood", "Mood and lighting"), ("framing", "Framing"))
Detail = app_commands.Range[str, 1, IMAGINE_MAX_DETAIL_CHARS]


def with_details(prompt: str, **details: Optional[str]) -> str:
    """The prompt, then each detail the user filled in. With none, the prompt as typed."""
    if not any(details.get(key) for key, _ in _DETAILS):
        return prompt
    parts = [prompt.strip().rstrip(".")]
    parts += [f"{label}: {details[key].strip().rstrip('.')}" for key, label in _DETAILS if details.get(key)]
    return ". ".join(parts) + ("." if len(parts) > 1 else "")
# How a refusal starts. The base is abliterated and the prompt forbids it, but
# a refusal drawn as an image would be worse than the user's own words.
_REFUSALS = ("i can't", "i cannot", "i can not", "i won't", "i'm sorry", "i am sorry", "sorry", "as an ai")


async def rewrite_prompt(proxy: ProxyClient, prompt: str, lora: Optional[list[dict]]) -> Optional[str]:
    """
    The prompt expanded for the image model, or None to send the original: the
    request failed, or what came back is empty, a refusal, or too long to be
    the one paragraph asked for.
    """
    try:
        raw = await proxy.chat(
            IMAGINE_REWRITE_MODEL,
            [{"role": "system", "content": load("imagine_rewrite")}, {"role": "user", "content": prompt}],
            lora=lora,
            temperature=IMAGINE_REWRITE_TEMPERATURE,
            max_tokens=IMAGINE_REWRITE_MAX_TOKENS,
        )
    except ProxyError as e:
        logger.warning("Prompt rewrite failed (%s); using the original", e)
        return None
    text = raw.strip().strip('"').strip()
    if not text or len(text) > IMAGINE_REWRITE_MAX_CHARS or text.lower().startswith(_REFUSALS):
        logger.warning("Unusable prompt rewrite %r; using the original", raw[:200])
        return None
    return text


def footer_text(user: str, size: str, rewrite_s: Optional[float], image_s: float, count: int = 1) -> str:
    """
    Who asked, the model, the size, and how long each step took as the user
    waited for it. The image time includes any model swap or cold start the
    proxy needed first. A rewrite's time shows even when its result was not
    usable, since it was still waited for.
    """
    parts = [f"Requested by {user}", IMAGINE_MODEL_LABEL, size]
    if rewrite_s is not None:
        parts.append(f"rewrite {rewrite_s:.1f} s")
    parts.append(f"image {image_s:.1f} s" if count == 1 else f"{count} images {image_s:.1f} s")
    return " · ".join(parts)


class ImagineCog(commands.Cog):
    def __init__(self, bot: commands.Bot):
        self.bot = bot

    @property
    def services(self):
        return self.bot.services

    @app_commands.command(name="imagine", description="Generate an image from a text description")
    @app_commands.describe(
        prompt="What to draw, e.g. a goose in a top hat, a goblin selling DVDs in a parking lot",
        style="Art style or medium, e.g. oil painting, pixel art, 35mm film photo, anime",
        mood="Mood and lighting, e.g. cozy golden hour, eerie fog, neon-lit night",
        framing="Camera and composition, e.g. close-up portrait, wide shot, seen from above",
        shape="Image shape, e.g. Portrait for a character, Landscape for a scene (default: Square)",
        rewrite="Let AI add detail first, e.g. True for a short or vague prompt. Adds ~10 s",
        count=f"How many images to make from the prompt, e.g. 3 to pick a favourite (default: 1, max {IMAGINE_MAX_IMAGES})",
    )
    @app_commands.choices(shape=_SHAPE_CHOICES)
    async def imagine(
        self,
        interaction: discord.Interaction,
        prompt: app_commands.Range[str, 1, IMAGINE_MAX_PROMPT_CHARS],
        # Required, so it is asked every time: users left it at its default.
        # Discord lists required options first, so it sits right after the prompt.
        rewrite: bool,
        count: app_commands.Range[int, 1, IMAGINE_MAX_IMAGES] = 1,
        style: Optional[Detail] = None,
        mood: Optional[Detail] = None,
        framing: Optional[Detail] = None,
        shape: Optional[app_commands.Choice[str]] = None,
    ):
        services = self.services
        if not await admit(interaction, services):
            return

        size = shape.value if shape else _DEFAULT_SIZE
        prompt = with_details(prompt, style=style, mood=mood, framing=framing)
        logger.info("Imagine from %s (%s): %r", interaction.user.name, size, prompt[:100])
        await interaction.response.defer(thinking=True)

        rewritten, rewrite_s = None, None
        if rewrite:
            # The bare base, every adapter at 0. Before discovery the adapters
            # are loaded unapplied anyway (lora-init-without-apply), so None is the same.
            try:
                lora = services.personas.lora(None)
            except LookupError:
                lora = None
            started = time.monotonic()
            rewritten = await rewrite_prompt(services.proxy, prompt, lora)
            rewrite_s = time.monotonic() - started
            if rewritten:
                logger.info("Imagine rewrite: %r", rewritten[:300])

        started = time.monotonic()
        try:
            pngs = await services.proxy.generate_image(rewritten or prompt, size, count)
        except ProxyError as e:
            logger.warning("Imagine failed: %s", e)
            await interaction.followup.send(f"⚠️ Couldn't generate that image: {e}")
            return
        image_s = time.monotonic() - started

        embed = discord.Embed(description=prompt[:4000])
        if rewritten:
            embed.add_field(name="Rewritten prompt", value=rewritten[:_EMBED_FIELD_MAX], inline=False)
        embed.set_footer(text=footer_text(interaction.user.display_name, size, rewrite_s, image_s, len(pngs)))
        if len(pngs) == 1:
            embed.set_image(url="attachment://imagine.png")
            files = [discord.File(io.BytesIO(pngs[0]), filename="imagine.png")]
        else:
            # An embed holds one image; several attachments show as a grid with the embed.
            files = [discord.File(io.BytesIO(png), filename=f"imagine_{n}.png") for n, png in enumerate(pngs, 1)]
        await interaction.followup.send(embed=embed, files=files)


async def setup(bot: commands.Bot) -> None:
    await bot.add_cog(ImagineCog(bot))
